def _apply_late_calibrator(raw_probability, calibrator):
    raw = np.clip(np.asarray(raw_probability, dtype=float), 1e-6, 1 - 1e-6)
    logits = np.log(raw / (1.0 - raw)).reshape(-1, 1)
    return np.asarray(calibrator.predict_proba(logits)[:, 1], dtype=float)


def _classification_metrics_for_scores(y_true, scores, threshold):
    y_true = np.asarray(y_true, dtype=int)
    scores = np.asarray(scores, dtype=float)
