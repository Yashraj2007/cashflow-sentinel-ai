"""## 9. PyTorch LSTM model and training loop

The recurrent input has shape `[batch_size, sequence_length, number_of_features]`. Each sequence contains prior invoices' encoded invoice-time features, their delay outcomes (scaled using the training target scaler), and the gap from that historic invoice to the target invoice date. The current invoice features plus online historical summary statistics go through a separate projection and are fused with the LSTM representation.

Huber/Smooth-L1 loss reduces sensitivity to very large delay outliers. Gradients are clipped, the best validation checkpoint is restored, and CPU is supported when no GPU is available.
"""

class LSTMDelayRegressor(nn.Module):
    def __init__(self, input_size, static_size, hidden_size=64, num_layers=2, dropout=0.2):
        super().__init__()
        self.hidden_size = hidden_size
        self.num_layers = num_layers
        self.lstm = nn.LSTM(
            input_size=input_size,
            hidden_size=hidden_size,
            num_layers=num_layers,
            batch_first=True,
            dropout=dropout if num_layers > 1 else 0.0,
        )
        self.static_projection = nn.Sequential(
            nn.Linear(static_size, hidden_size),
            nn.ReLU(),
            nn.Dropout(dropout),
        )
        self.regression_head = nn.Sequential(
            nn.Linear(hidden_size * 2, hidden_size),
            nn.ReLU(),
            nn.Dropout(dropout),
            nn.Linear(hidden_size, 1),
        )
        self._initialize_weights()

    def _initialize_weights(self):
        for name, param in self.lstm.named_parameters():
            if "weight_ih" in name:
                nn.init.xavier_uniform_(param.data)
            elif "weight_hh" in name:
                nn.init.orthogonal_(param.data)
            elif "bias" in name:
                nn.init.zeros_(param.data)
        for module in self.modules():
            if isinstance(module, nn.Linear):
                nn.init.xavier_uniform_(module.weight)
                if module.bias is not None:
                    nn.init.zeros_(module.bias)

    def forward(self, sequence_x, current_x):
        _, (hidden, _) = self.lstm(sequence_x)
        sequence_embedding = hidden[-1]
        current_embedding = self.static_projection(current_x)
        combined = torch.cat([sequence_embedding, current_embedding], dim=1)
        return self.regression_head(combined).squeeze(1)


def build_lstm_arrays(target_indices, sequence_length):
    """Materialize fixed-length historical sequences for selected target rows only."""
    target_indices = np.asarray(target_indices, dtype=int)
    eligible = target_indices[history_counts[target_indices] >= sequence_length]
    n_features = X_base.shape[1] + 2
    if len(eligible) == 0:
        return (np.empty((0, sequence_length, n_features), dtype=np.float32),
                np.empty((0, X_tabular.shape[1]), dtype=np.float32),
                np.empty((0,), dtype=np.float32), eligible)

    X_seq = np.empty((len(eligible), sequence_length, n_features), dtype=np.float32)
    X_current = X_tabular[eligible].astype(np.float32, copy=True)
    y_scaled_values = y_scaled[eligible].astype(np.float32, copy=True)
    for row_number, target_idx in enumerate(eligible):
        hist_idx = history_indices[target_idx][-sequence_length:]
        gaps = (df.loc[target_idx, "Doc_Date"] - df.loc[hist_idx, "Doc_Date"]).dt.days.to_numpy(dtype=float)
        gaps = np.maximum(gaps, 0.0)
        hist_y_scaled = y_scaled[hist_idx].reshape(-1, 1)
        gap_feature = np.log1p(gaps).reshape(-1, 1).astype(np.float32)
        X_seq[row_number] = np.concatenate([X_base[hist_idx], hist_y_scaled, gap_feature], axis=1)
    return X_seq, X_current, y_scaled_values, eligible


def train_lstm_for_length(sequence_length):
    train_seq, train_current, train_target_scaled, eligible_train = build_lstm_arrays(train_idx, sequence_length)
    val_seq, val_current, val_target_scaled, eligible_val = build_lstm_arrays(val_idx, sequence_length)
    if len(eligible_train) < 20 or len(eligible_val) < 10:
        print(f"Skipping sequence length {sequence_length}: insufficient eligible train/validation rows ({len(eligible_train)}, {len(eligible_val)}).")
        return None

    train_dataset = TensorDataset(
        torch.from_numpy(train_seq), torch.from_numpy(train_current), torch.from_numpy(train_target_scaled)
    )
    generator = torch.Generator().manual_seed(SEED + sequence_length)
    train_loader = DataLoader(train_dataset, batch_size=BATCH_SIZE, shuffle=True, generator=generator, num_workers=0)

    model = LSTMDelayRegressor(
        input_size=train_seq.shape[2], static_size=train_current.shape[1],
        hidden_size=HIDDEN_SIZE, num_layers=NUM_LAYERS, dropout=DROPOUT
    ).to(DEVICE)
    criterion = nn.SmoothL1Loss()
    optimizer = torch.optim.Adam(model.parameters(), lr=LEARNING_RATE)

    history = {"train_loss": [], "validation_loss": [], "validation_mae_days": []}
    best_mae = float("inf")
    best_state = None
    best_epoch = 0
    patience_left = EARLY_STOPPING_PATIENCE
    fit_start = time.time()
    val_current_t = torch.from_numpy(val_current).to(DEVICE)
    val_seq_t = torch.from_numpy(val_seq).to(DEVICE)
    val_target_t = torch.from_numpy(val_target_scaled).to(DEVICE)

    for epoch in range(1, MAX_EPOCHS + 1):
        model.train()
        train_loss_sum, train_count = 0.0, 0
        for batch_seq, batch_current, batch_target in train_loader:
            batch_seq = batch_seq.to(DEVICE)
            batch_current = batch_current.to(DEVICE)
            batch_target = batch_target.to(DEVICE)
            optimizer.zero_grad(set_to_none=True)
            pred_scaled = model(batch_seq, batch_current)
            loss = criterion(pred_scaled, batch_target)
            loss.backward()
            torch.nn.utils.clip_grad_norm_(model.parameters(), GRADIENT_CLIP_NORM)
            optimizer.step()
            train_loss_sum += float(loss.item()) * len(batch_target)
            train_count += len(batch_target)

        train_loss = train_loss_sum / max(train_count, 1)
        model.eval()
        with torch.no_grad():
            val_pred_scaled = model(val_seq_t, val_current_t)
            val_loss = float(criterion(val_pred_scaled, val_target_t).item())
            val_pred_days = target_scaler.inverse_transform(val_pred_scaled.detach().cpu().numpy().reshape(-1, 1)).ravel()
            val_mae = float(mean_absolute_error(y[eligible_val], val_pred_days))

        history["train_loss"].append(train_loss)
        history["validation_loss"].append(val_loss)
        history["validation_mae_days"].append(val_mae)

        if val_mae < best_mae - 1e-5:
            best_mae = val_mae
            best_epoch = epoch
            best_state = {k: v.detach().cpu().clone() for k, v in model.state_dict().items()}
            patience_left = EARLY_STOPPING_PATIENCE
        else:
            patience_left -= 1

        if epoch == 1 or epoch % 5 == 0:
            print(f"seq={sequence_length} | epoch {epoch:02d} | train Huber={train_loss:.4f} | val MAE={val_mae:.3f} days")
        if patience_left <= 0:
            print(f"Early stopping at epoch {epoch}; best epoch={best_epoch}, val MAE={best_mae:.3f} days.")
            break

    if best_state is not None:
        model.load_state_dict(best_state)
    model = model.to("cpu")
    elapsed = time.time() - fit_start
    parameter_count = sum(p.numel() for p in model.parameters() if p.requires_grad)
    print(f"Finished seq={sequence_length}: {len(eligible_train):,} train sequences, {len(eligible_val):,} validation sequences, {elapsed:.1f}s, {parameter_count:,} parameters.")

    result = {
        "model": model,
        "history": history,
        "sequence_length": sequence_length,
        "eligible_train": eligible_train,
        "eligible_val": eligible_val,
        "best_epoch": best_epoch,
        "best_val_mae_eligible": best_mae,
        "training_seconds": elapsed,
        "parameter_count": parameter_count,
    }
    del train_seq, train_current, train_target_scaled, val_seq, val_current, val_target_scaled
    del train_dataset, train_loader, val_current_t, val_seq_t, val_target_t
    gc.collect()
    if torch.cuda.is_available():
        torch.cuda.empty_cache()
    return result


def predict_lstm_model(model, target_indices, sequence_length, batch_size=512):
    seq, current, _, eligible = build_lstm_arrays(target_indices, sequence_length)
    if len(eligible) == 0:
        return eligible, np.array([], dtype=float)
    model = model.to(DEVICE).eval()
    preds_scaled = []
    with torch.no_grad():
        for start in range(0, len(eligible), batch_size):
            end = min(start + batch_size, len(eligible))
            xb_seq = torch.from_numpy(seq[start:end]).to(DEVICE)
            xb_cur = torch.from_numpy(current[start:end]).to(DEVICE)
            preds_scaled.append(model(xb_seq, xb_cur).detach().cpu().numpy())
    preds_scaled = np.concatenate(preds_scaled).reshape(-1, 1)
    preds_days = target_scaler.inverse_transform(preds_scaled).ravel()
    model = model.to("cpu")
    del seq, current
    gc.collect()
    return eligible, preds_days

