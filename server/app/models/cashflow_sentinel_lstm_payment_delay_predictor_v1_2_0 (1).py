"""## 6. Build prediction-time features and event-time-safe customer histories

The sequence model uses the most recent 3, 5, or 10 customer invoices whose payment outcome was already known as of the current invoice date. A previous invoice becomes eligible only on `max(Clearing_date, Doc_Date + 1 day)`. This prevents same-day and future invoice outcomes from leaking into the current prediction.

The current invoice's known features are passed separately to the LSTM regressor, so the model can combine customer history with the amount, terms, payment method, and calendar details of the invoice being predicted.
"""

TARGET_COL = "Days_Overdue_Delay"
NUMERIC_FEATURES = [
    "amount_signed_log1p", "payment_term_days", "rank_log1p", "doc_year",
    "doc_month_sin", "doc_month_cos", "doc_weekday_sin", "doc_weekday_cos",
    "due_month_sin", "due_month_cos", "due_weekday_sin", "due_weekday_cos",
]
CATEGORICAL_FEATURES = ["Payment_Method_description", "Region", "City", "Zipcode"]
BASE_FEATURE_COLUMNS = NUMERIC_FEATURES + CATEGORICAL_FEATURES
SUMMARY_COLUMNS = [
    "history_count_log", "history_delay_mean", "history_delay_median",
    "history_delay_std", "history_on_time_rate", "history_last_delay",
    "history_days_since_last_invoice_log",
]

def build_known_features(frame):
    """Create only invoice-time features; does not read target or clearing columns."""
    out = pd.DataFrame(index=frame.index)
    doc = pd.to_datetime(frame["Doc_Date"], errors="coerce") if "Doc_Date" in frame else pd.Series(pd.NaT, index=frame.index)
    due = pd.to_datetime(frame["Net_Due_Date"], errors="coerce") if "Net_Due_Date" in frame else pd.Series(pd.NaT, index=frame.index)
    amount = pd.to_numeric(frame["Amount"], errors="coerce") if "Amount" in frame else pd.Series(np.nan, index=frame.index)
    amount = amount.fillna(0.0)
    if "Payment_Term" in frame:
        term = pd.to_numeric(frame["Payment_Term"], errors="coerce")
    else:
        term = (due - doc).dt.days.astype(float)
    derived_term = (due - doc).dt.days.astype(float)
    term = term.where(term.notna(), derived_term)
    if "Rank_of_order_by_customer" in frame:
        rank = pd.to_numeric(frame["Rank_of_order_by_customer"], errors="coerce")
    else:
        rank = pd.Series(np.arange(1, len(frame) + 1), index=frame.index, dtype=float)

    doc_month = doc.dt.month.astype(float)
    due_month = due.dt.month.astype(float)
    doc_weekday = doc.dt.dayofweek.astype(float)
    due_weekday = due.dt.dayofweek.astype(float)
    out["amount_signed_log1p"] = np.sign(amount) * np.log1p(np.abs(amount))
    out["payment_term_days"] = term
    out["rank_log1p"] = np.log1p(rank.clip(lower=0))
    out["doc_year"] = doc.dt.year.astype(float)
    out["doc_month_sin"] = np.sin(2 * np.pi * doc_month / 12)
    out["doc_month_cos"] = np.cos(2 * np.pi * doc_month / 12)
    out["doc_weekday_sin"] = np.sin(2 * np.pi * doc_weekday / 7)
    out["doc_weekday_cos"] = np.cos(2 * np.pi * doc_weekday / 7)
    out["due_month_sin"] = np.sin(2 * np.pi * due_month / 12)
    out["due_month_cos"] = np.cos(2 * np.pi * due_month / 12)
    out["due_weekday_sin"] = np.sin(2 * np.pi * due_weekday / 7)
    out["due_weekday_cos"] = np.cos(2 * np.pi * due_weekday / 7)
    for col in CATEGORICAL_FEATURES:
        if col in frame.columns:
            out[col] = frame[col].astype("string").fillna("Unknown").astype(str)
        else:
            out[col] = "Unknown"
    return out[BASE_FEATURE_COLUMNS]

