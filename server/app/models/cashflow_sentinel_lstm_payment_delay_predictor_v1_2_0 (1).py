# Maintain online running statistics and a heap keyed by chronological row position.
def _add_to_median_heaps(low_heap, high_heap, value):
    value = float(value)
    if not low_heap or value <= -low_heap[0]:
        heapq.heappush(low_heap, -value)
    else:
        heapq.heappush(high_heap, value)
    if len(low_heap) > len(high_heap) + 1:
        heapq.heappush(high_heap, -heapq.heappop(low_heap))
    elif len(high_heap) > len(low_heap):
        heapq.heappush(low_heap, -heapq.heappop(high_heap))

def _heap_median(low_heap, high_heap):
    if not low_heap:
        return 0.0
    if len(low_heap) > len(high_heap):
        return float(-low_heap[0])
    return float((-low_heap[0] + high_heap[0]) / 2.0)

def build_temporal_histories(frame, max_sequence_length=10):
    """Return per-row historical indices and summary features, with strict event-time eligibility."""
    n = len(frame)
    histories = [np.array([], dtype=int) for _ in range(n)]
    summaries = np.zeros((n, len(SUMMARY_COLUMNS)), dtype=np.float32)
    counts = np.zeros(n, dtype=np.int32)
    frame_delay = frame[TARGET_COL].astype(float).to_numpy()

    for _, cust_group in frame.groupby("Cust_Num", sort=False, dropna=False):
        ordered = cust_group.sort_values(
            ["Doc_Date", "Rank_of_order_by_customer", "Document_No"], kind="mergesort"
        )
        global_indices = ordered.index.to_numpy(dtype=int)
        local_doc = ordered["Doc_Date"].to_numpy(dtype="datetime64[ns]")
        local_clear = ordered["Clearing_date"].to_numpy(dtype="datetime64[ns]")
        local_y = frame_delay[global_indices]
        # Strictly earlier invoice date + payment outcome already cleared.
        eligible_at = np.maximum(local_clear, local_doc + np.timedelta64(1, "D"))
        activation_order = np.argsort(eligible_at, kind="stable")
        activation_ptr = 0
        active_latest_heap = []  # (-local chronological position, local position)
        low_heap, high_heap = [], []
        running_sum = 0.0
        running_sum_sq = 0.0
        on_time_count = 0
        active_count = 0

        for local_target_pos, global_target_idx in enumerate(global_indices):
            target_date = local_doc[local_target_pos]
            while activation_ptr < len(activation_order):
                local_hist_pos = int(activation_order[activation_ptr])
                if eligible_at[local_hist_pos] > target_date:
                    break
                # The activation rule guarantees Doc_Date < target_date.
                heapq.heappush(active_latest_heap, (-local_hist_pos, local_hist_pos))
                delay_value = float(local_y[local_hist_pos])
                active_count += 1
                running_sum += delay_value
                running_sum_sq += delay_value * delay_value
                if delay_value <= 0:
                    on_time_count += 1
                _add_to_median_heaps(low_heap, high_heap, delay_value)
                activation_ptr += 1

            counts[global_target_idx] = active_count
            top_local_positions = []
            for _ in range(min(max_sequence_length, len(active_latest_heap))):
                _, local_pos = heapq.heappop(active_latest_heap)
                top_local_positions.append(local_pos)
            for local_pos in top_local_positions:
                heapq.heappush(active_latest_heap, (-local_pos, local_pos))
            top_local_positions.sort()
            histories[global_target_idx] = global_indices[np.asarray(top_local_positions, dtype=int)] if top_local_positions else np.array([], dtype=int)

            if active_count:
                mean_val = running_sum / active_count
                variance = max(running_sum_sq / active_count - mean_val * mean_val, 0.0)
                most_recent_local = top_local_positions[-1] if top_local_positions else None
                last_delay = float(local_y[most_recent_local]) if most_recent_local is not None else 0.0
                last_gap_days = max(0, int((target_date - local_doc[most_recent_local]) / np.timedelta64(1, "D"))) if most_recent_local is not None else 0
                summary_values = [
                    np.log1p(active_count), mean_val, _heap_median(low_heap, high_heap),
                    np.sqrt(variance), on_time_count / active_count, last_delay,
                    np.log1p(last_gap_days)
                ]
                summaries[global_target_idx] = np.asarray(summary_values, dtype=np.float32)

    return histories, summaries, counts

