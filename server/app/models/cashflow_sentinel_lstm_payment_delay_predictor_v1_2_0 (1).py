def _late_probability_from_models(current_tab):
    """
    Return the probability that an invoice will be paid late.

    Expects current_tab to contain the feature row in the same
    format used to train classification_model.
    """
    model = globals().get("classification_model", None)

    if model is None:
        return np.array([np.nan], dtype=float)

    # Ensure the input is a one-row DataFrame.
    if isinstance(current_tab, pd.Series):
        current_tab = current_tab.to_frame().T
    elif not isinstance(current_tab, pd.DataFrame):
        current_tab = pd.DataFrame(current_tab)

    if len(current_tab) != 1:
        raise ValueError(
            "Expected exactly one invoice row for probability prediction."
        )

    # Preferred method: obtain the probability for the late class.
    if hasattr(model, "predict_proba"):
        probabilities = np.asarray(model.predict_proba(current_tab))

        if probabilities.ndim != 2 or probabilities.shape[0] != 1:
            raise ValueError(
                "Unexpected output shape from classification_model.predict_proba()."
            )

        classes = getattr(model, "classes_", None)

        if classes is None and hasattr(model, "named_steps"):
            # Support sklearn Pipelines whose final estimator has classes_.
            final_estimator = list(model.named_steps.values())[-1]
            classes = getattr(final_estimator, "classes_", None)

        if classes is None:
            if probabilities.shape[1] == 2:
                return np.array([float(probabilities[0, 1])])
            raise ValueError(
                "Cannot identify the late-payment class. Check model.classes_."
            )

        classes = np.asarray(classes).reshape(-1)
        late_indices = np.flatnonzero(classes == 1)

        if len(late_indices) == 0:
            # Some classifiers use Boolean labels.
            late_indices = np.flatnonzero(classes == True)

        if len(late_indices) == 0:
            raise ValueError(
                f"Late class 1 not found in classifier classes: {classes!r}. "
                "Update the positive-class label to match your training labels."
            )

        return np.array([
            float(probabilities[0, late_indices[0]])
        ])

    # Alternative: convert a decision score to a probability-like value.
    # This is a sigmoid-transformed score, NOT a calibrated probability.
    if hasattr(model, "decision_function"):
        scores = np.asarray(model.decision_function(current_tab)).reshape(-1)

        if len(scores) != 1:
            raise ValueError("Expected one classification decision score.")

        score = float(np.clip(scores[0], -500, 500))
        return np.array([1.0 / (1.0 + np.exp(-score))])

    # Do not fabricate a probability for a classifier without probability
    # or decision-score support.
    return np.array([np.nan], dtype=float)

