class LSTMDelayRegressor(nn.Module):
    def __init__(self, input_size, static_size, hidden_size=64, num_layers=2, dropout=0.2):
        super().__init__()
        self.lstm = nn.LSTM(input_size, hidden_size, num_layers=num_layers, batch_first=True,
                            dropout=dropout if num_layers > 1 else 0.0)
        self.static_projection = nn.Sequential(nn.Linear(static_size, hidden_size), nn.ReLU(), nn.Dropout(dropout))
        self.regression_head = nn.Sequential(nn.Linear(hidden_size * 2, hidden_size), nn.ReLU(),
                                             nn.Dropout(dropout), nn.Linear(hidden_size, 1))
    def forward(self, sequence_x, current_x):
        _, (hidden, _) = self.lstm(sequence_x)
        current_embedding = self.static_projection(current_x)
        return self.regression_head(torch.cat([hidden[-1], current_embedding], dim=1)).squeeze(1)

