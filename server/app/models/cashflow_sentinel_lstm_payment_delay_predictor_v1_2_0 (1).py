"""## 13. Reusable prediction function

`predict_payment_delay(customer_history, invoice_details)` expects a current invoice with known details and a history table containing prior invoice records. The function independently filters history to outcomes that were cleared by the target invoice date. In live integration, pass only actually observed historical outcomes; for retrospective backtesting, the clearing-date filter simulates what was known at each historical prediction time.

The raw predicted delay (including negative values) is preserved. The estimated payment date starts as `due_date + round(predicted_delay_days)`, but if that date would fall before `doc_date`, the output date is clamped to the invoice date and the `payment_date_rule` field reports the safeguard. The fractional delay remains available separately from integer calendar-day arithmetic. The date is an estimate, not a guarantee.
"""

def _prepare_single_invoice_row(invoice_details, history_frame):
    row = dict(invoice_details)
    for required in ["Doc_Date", "Net_Due_Date", "Amount"]:
        if required not in row or pd.isna(row[required]):
            raise ValueError(f"invoice_details must include a non-missing '{required}'.")
    row["Doc_Date"] = pd.to_datetime(row["Doc_Date"], errors="coerce")
    row["Net_Due_Date"] = pd.to_datetime(row["Net_Due_Date"], errors="coerce")
    if pd.isna(row["Doc_Date"]) or pd.isna(row["Net_Due_Date"]):
        raise ValueError("Doc_Date and Net_Due_Date must be valid dates.")
    if "Payment_Term" not in row or pd.isna(row.get("Payment_Term")):
        row["Payment_Term"] = int((row["Net_Due_Date"] - row["Doc_Date"]).days)
    if "Rank_of_order_by_customer" not in row or pd.isna(row.get("Rank_of_order_by_customer")):
        row["Rank_of_order_by_customer"] = len(history_frame) + 1
    for col in CATEGORICAL_FEATURES:
        row.setdefault(col, "Unknown")
    return row


def _raw_summary_from_eligible_history(history_frame, target_doc_date):
    delays = pd.to_numeric(history_frame.get(TARGET_COL, pd.Series(dtype=float)), errors="coerce").dropna().to_numpy(dtype=float)
    count = len(delays)
    if count == 0:
        return np.zeros((1, len(SUMMARY_COLUMNS)), dtype=np.float32), delays
    sort_cols = [c for c in ["Doc_Date", "Rank_of_order_by_customer", "Document_No"] if c in history_frame.columns]
    sorted_history = history_frame.sort_values(sort_cols, kind="mergesort") if sort_cols else history_frame
    sorted_delays = pd.to_numeric(sorted_history[TARGET_COL], errors="coerce").dropna().to_numpy(dtype=float)
    last_row = sorted_history.iloc[-1]
    last_doc_date = pd.to_datetime(last_row["Doc_Date"])
    gap = max(0, int((target_doc_date - last_doc_date).days))
    summary = np.asarray([[
        np.log1p(count), float(np.mean(delays)), float(np.median(delays)),
        float(np.std(delays)), float(np.mean(delays <= 0)), float(sorted_delays[-1]),
        np.log1p(gap)
    ]], dtype=np.float32)
    return summary, delays


def predict_payment_delay(customer_history, invoice_details):
    """Predict delay days for one invoice without using its actual outcome."""
    if customer_history is None:
        customer_history = pd.DataFrame()
    elif not isinstance(customer_history, pd.DataFrame):
        customer_history = pd.DataFrame(customer_history)
    hist = customer_history.copy()
    current = _prepare_single_invoice_row(invoice_details, hist)
    target_doc_date = pd.to_datetime(current["Doc_Date"])

    # If customer IDs are supplied, restrict the context to the current customer's records.
    if "Cust_Num" in hist.columns and current.get("Cust_Num") is not None:
        hist = hist.loc[hist["Cust_Num"].astype(str) == str(current["Cust_Num"])].copy()

    for col in ["Doc_Date", "Clearing_date"]:
        if col in hist.columns:
            hist[col] = pd.to_datetime(hist[col], errors="coerce")
    if TARGET_COL not in hist.columns:
        hist[TARGET_COL] = np.nan
    hist[TARGET_COL] = pd.to_numeric(hist[TARGET_COL], errors="coerce")
    if not {"Doc_Date", "Clearing_date"}.issubset(hist.columns):
        hist = hist.iloc[0:0].copy()
    else:
        hist = hist.loc[
            hist["Doc_Date"].notna() & hist["Clearing_date"].notna() & hist[TARGET_COL].notna()
            & (hist["Doc_Date"] < target_doc_date) & (hist["Clearing_date"] <= target_doc_date)
        ].copy()
    if "Rank_of_order_by_customer" not in hist.columns:
        hist["Rank_of_order_by_customer"] = np.arange(1, len(hist) + 1)
    for col in CATEGORICAL_FEATURES:
        if col not in hist.columns:
            hist[col] = "Unknown"
    if "Payment_Term" not in hist.columns:
        hist["Payment_Term"] = (hist["Net_Due_Date"] - hist["Doc_Date"]).dt.days if "Net_Due_Date" in hist.columns else np.nan
    if "Amount" not in hist.columns:
        hist["Amount"] = 0.0
    if "Net_Due_Date" not in hist.columns:
        hist["Net_Due_Date"] = hist["Doc_Date"]
    if "Document_No" not in hist.columns:
        hist["Document_No"] = np.arange(len(hist)).astype(str)

    history_sort_cols = [c for c in ["Doc_Date", "Rank_of_order_by_customer", "Document_No"] if c in hist.columns]
    if history_sort_cols:
        hist = hist.sort_values(history_sort_cols, kind="mergesort").reset_index(drop=True)
    current_df = pd.DataFrame([current])
    # Ensure all feature columns exist before using the fitted transformer.
    for col in ["Payment_Term", "Rank_of_order_by_customer", "Amount", "Doc_Date", "Net_Due_Date"] + CATEGORICAL_FEATURES:
        if col not in current_df.columns:
            current_df[col] = "Unknown" if col in CATEGORICAL_FEATURES else np.nan
    current_df["Doc_Date"] = pd.to_datetime(current_df["Doc_Date"], errors="coerce")
    current_df["Net_Due_Date"] = pd.to_datetime(current_df["Net_Due_Date"], errors="coerce")

    combined = pd.concat([hist, current_df], ignore_index=True, sort=False)
    base_encoded = np.asarray(preprocessor.transform(build_known_features(combined)), dtype=np.float32)
    current_base = base_encoded[-1:]
    hist_base = base_encoded[:-1]
    summary_raw, hist_delays = _raw_summary_from_eligible_history(hist, target_doc_date)
    summary_scaled = summary_scaler.transform(summary_raw).astype(np.float32)
    current_tab = np.concatenate([current_base, summary_scaled], axis=1).astype(np.float32)

    chosen_name = selected_model_name
    status = "estimated"
    used_model_name = chosen_name
    predicted_raw = None
    history_used = 0

    def _predict_tabular_name(name):
        nonlocal history_used
        if name == "GlobalMedian":
            history_used = 0
            return global_median
        if name == "CustomerHistoryMedian":
            history_used = int(len(hist_delays))
            return float(np.median(hist_delays)) if len(hist_delays) else global_median
        history_used = int(len(hist_delays))
        if name not in tabular_models:
            raise KeyError(f"Tabular model '{name}' is not available in this notebook session.")
        return float(tabular_models[name].predict(current_tab)[0])

    if chosen_name.startswith("LSTM_seq"):
        seq_len = int(chosen_name.replace("LSTM_seq", ""))
        if len(hist) >= seq_len:
            selected_hist = hist.tail(seq_len).copy()
            hist_base_selected = hist_base[-seq_len:]
            gaps = (target_doc_date - pd.to_datetime(selected_hist["Doc_Date"])).dt.days.to_numpy(dtype=float)
            gaps = np.maximum(gaps, 0.0)
            delays_scaled = target_scaler.transform(selected_hist[TARGET_COL].to_numpy(dtype=float).reshape(-1, 1)).astype(np.float32)
            seq = np.concatenate([hist_base_selected, delays_scaled, np.log1p(gaps).reshape(-1, 1).astype(np.float32)], axis=1)
            model = lstm_results[chosen_name]["model"].to(DEVICE).eval()
            with torch.no_grad():
                pred_scaled = model(torch.from_numpy(seq[None, :, :]).to(DEVICE), torch.from_numpy(current_tab).to(DEVICE)).detach().cpu().numpy().reshape(-1, 1)
            predicted_raw = float(target_scaler.inverse_transform(pred_scaled)[0, 0])
            model.to("cpu")
            history_used = seq_len
        else:
            status = "estimated_fallback_insufficient_history"
            used_model_name = best_fallback_name
            predicted_raw = _predict_tabular_name(best_fallback_name)
    else:
        predicted_raw = _predict_tabular_name(chosen_name)

    # Probability refers to the target-derived label (delay days > 0), not the inconsistent source DelayFlag.
    late_probability = None
    if classification_model is not None:
        late_probability_array = _late_probability_from_models(current_tab)
        late_probability = float(late_probability_array[0])

    rounded_delay_for_date = int(np.rint(predicted_raw))
    due_timestamp = pd.to_datetime(current["Net_Due_Date"]).normalize()
    invoice_timestamp = pd.to_datetime(current["Doc_Date"]).normalize()
    raw_payment_timestamp = due_timestamp + pd.to_timedelta(rounded_delay_for_date, unit="D")
    # Business safeguard: never emit a predicted receipt date before this invoice was created.
    if raw_payment_timestamp < invoice_timestamp:
        payment_timestamp = invoice_timestamp
        payment_date_rule = "clamped_to_invoice_date"
    else:
        payment_timestamp = raw_payment_timestamp
        payment_date_rule = "due_date_plus_rounded_predicted_delay"
    predicted_payment_date = payment_timestamp.date().isoformat()
    due_date_string = due_timestamp.date().isoformat()
    invoice_date_string = invoice_timestamp.date().isoformat()
    return {
        "customer_id": str(current.get("Cust_Num", "UNKNOWN")),
        "invoice_id": str(current.get("Document_No", "UNKNOWN")),
        "doc_date": invoice_date_string,
        "due_date": due_date_string,
        "predicted_delay_days": round(float(predicted_raw), 4),
        "predicted_delay_days_for_calendar": rounded_delay_for_date,
        "predicted_payment_date": predicted_payment_date,
        "payment_date_rule": payment_date_rule,
        "model_name": used_model_name,
        "prediction_status": status,
        "history_invoices_used": int(history_used),
        "known_history_invoices": int(len(hist_delays)),
        "probability_delay_gt_zero": late_probability,
        "probability_score_calibrated": bool(classification_calibrator is not None and late_probability is not None),
        "late_payment_risk_threshold": float(best_threshold) if classification_model is not None else None,
        "predicted_late_payment": bool(late_probability >= best_threshold) if late_probability is not None else None,
        "date_is_estimate_not_guarantee": True,
        "limitations": "Trained on historical completed invoices; estimate can be wrong and may shift with customer behaviour or business conditions."
    }

