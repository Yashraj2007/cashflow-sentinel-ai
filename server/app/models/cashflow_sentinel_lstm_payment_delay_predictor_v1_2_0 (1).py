def _summary_from_history(history, target_doc_date, summary_columns):
    if history.empty:
        return np.zeros((1, len(summary_columns)), dtype=np.float32), np.array([], dtype=float)
    delays = pd.to_numeric(history["Days_Overdue_Delay"], errors="coerce").dropna().to_numpy(dtype=float)
    if not len(delays):
        return np.zeros((1, len(summary_columns)), dtype=np.float32), delays
    sort_cols = [c for c in ["Doc_Date", "Rank_of_order_by_customer", "Document_No"] if c in history.columns]
    ordered = history.sort_values(sort_cols, kind="mergesort") if sort_cols else history
    last = ordered.iloc[-1]
    gap = max(0, int((target_doc_date - pd.to_datetime(last["Doc_Date"])).days))
    s = {
        "history_count_log": np.log1p(len(delays)),
        "history_delay_mean": np.mean(delays),
        "history_delay_median": np.median(delays),
        "history_delay_std": np.std(delays),
        "history_on_time_rate": np.mean(delays <= 0),
        "history_last_delay": float(pd.to_numeric(pd.Series([last["Days_Overdue_Delay"]]), errors="coerce").iloc[0]),
        "history_days_since_last_invoice_log": np.log1p(gap),
    }
    return np.asarray([[s[c] for c in summary_columns]], dtype=np.float32), delays

