def calibrate_prefitted_classifier(fitted_model, X_calibration, y_calibration):
    """Calibrate an already-fitted base model on a separate later time interval."""
    if len(np.unique(np.asarray(y_calibration))) < 2:
        return fitted_model, False, "not_calibrated_single_class_calibration_window"
    try:
        from sklearn.frozen import FrozenEstimator
        calibrated = CalibratedClassifierCV(
            estimator=FrozenEstimator(fitted_model), method="sigmoid"
        )
        calibrated.fit(X_calibration, y_calibration)
        return calibrated, True, "sigmoid"
    except (ImportError, TypeError):
        try:
            calibrated = CalibratedClassifierCV(
                estimator=fitted_model, method="sigmoid", cv="prefit"
            )
        except TypeError:
            calibrated = CalibratedClassifierCV(
                base_estimator=fitted_model, method="sigmoid", cv="prefit"
            )
        calibrated.fit(X_calibration, y_calibration)
        return calibrated, True, "sigmoid"

def positive_class_score(model, X):
    probabilities = model.predict_proba(X)
    classes = list(model.classes_)
    if 1 not in classes:
        return np.zeros(len(X), dtype=float)
    return probabilities[:, classes.index(1)]

def best_f1_threshold(y_true, scores):
    """Reference threshold only; retained to compare against the old max-F1 policy."""
    precision, recall, thresholds = precision_recall_curve(y_true, scores)
    if len(thresholds) == 0:
        return 0.5, float(f1_score(y_true, np.asarray(scores) >= 0.5, zero_division=0))
    denominator = precision[:-1] + recall[:-1]
    f1_values = np.divide(
        2 * precision[:-1] * recall[:-1], denominator,
        out=np.zeros_like(denominator), where=denominator > 0
    )
    best_idx = int(np.nanargmax(f1_values))
    return float(thresholds[best_idx]), float(f1_values[best_idx])

def choose_operating_threshold(y_true, scores, min_precision=MIN_VALIDATION_PRECISION_TARGET):
    """Maximize validation recall subject to min precision and a minimum alert count.

    If the constraint cannot be met, use the best F0.5 among thresholds meeting the
    alert-count guard and explicitly mark that the configured precision target failed.
    This is a policy choice to reduce false alarms, not a guarantee about future periods.
    """
    y_true = np.asarray(y_true, dtype=int)
    scores = np.asarray(scores, dtype=float)
    precision, recall, thresholds = precision_recall_curve(y_true, scores)
    if len(thresholds) == 0:
        return 1.000001, {
            "policy_status": "no_threshold_candidates",
            "minimum_precision_target": float(min_precision),
            "minimum_precision_target_met": False,
            "validation_precision": 0.0,
            "validation_recall": 0.0,
            "validation_f1": 0.0,
            "validation_specificity": 1.0,
            "validation_false_positive_rate": 0.0,
            "validation_predicted_positive_count": 0,
            "selection_rule": "no candidate scores; default to all-negative decisions",
        }

    predicted_counts = np.array([(scores >= threshold).sum() for threshold in thresholds], dtype=int)
    minimum_count = max(int(MIN_VALIDATION_PREDICTED_POSITIVES), int(np.ceil(0.01 * len(y_true))))
    eligible = np.where((precision[:-1] >= min_precision) & (predicted_counts >= minimum_count))[0]

    if len(eligible):
        # Highest recall, then precision, then threshold (deterministic tie-break).
        best_idx = max(eligible, key=lambda i: (recall[i], precision[i], thresholds[i]))
        policy_status = "minimum_precision_target_met"
        selection_rule = "maximize validation recall subject to minimum precision and alert-count guard"
        target_met = True
    else:
        # Explicit fallback: favor precision more than recall; do not hide failed target.
        b2 = 0.25  # beta=0.5 -> beta^2=0.25
        denominator = b2 * precision[:-1] + recall[:-1]
        f_beta = np.divide(
            (1 + b2) * precision[:-1] * recall[:-1], denominator,
            out=np.zeros_like(denominator), where=denominator > 0
        )
        fallback = np.where(predicted_counts >= minimum_count)[0]
        if len(fallback):
            best_idx = max(fallback, key=lambda i: (f_beta[i], precision[i], thresholds[i]))
            policy_status = "precision_target_not_met_fallback_f0_5"
            selection_rule = "precision target infeasible; fallback to max validation F0.5 subject to alert-count guard"
        else:
            best_idx = int(np.argmax(thresholds))
            policy_status = "precision_target_not_met_fallback_all_negative"
            selection_rule = "precision target infeasible; fallback to threshold with minimum alert rate"
        target_met = False

    threshold = float(thresholds[best_idx])
    predictions = (scores >= threshold).astype(int)
    tn, fp, fn, tp = confusion_matrix(y_true, predictions, labels=[0, 1]).ravel()
    validation_precision = float(precision_score(y_true, predictions, zero_division=0))
    validation_recall = float(recall_score(y_true, predictions, zero_division=0))
    specificity = float(tn / (tn + fp)) if (tn + fp) else float("nan")
    fpr = float(fp / (fp + tn)) if (fp + tn) else float("nan")
    details = {
        "policy_status": policy_status,
        "minimum_precision_target": float(min_precision),
        "minimum_precision_target_met": bool(target_met and validation_precision >= min_precision),
        "validation_precision": validation_precision,
        "validation_recall": validation_recall,
        "validation_f1": float(f1_score(y_true, predictions, zero_division=0)),
        "validation_specificity": specificity,
        "validation_false_positive_rate": fpr,
        "validation_predicted_positive_count": int(predictions.sum()),
        "validation_tn": int(tn), "validation_fp": int(fp),
        "validation_fn": int(fn), "validation_tp": int(tp),
        "selection_rule": selection_rule,
    }
    return threshold, details

